#!/usr/bin/env python3
"""contracts/events/catalog.yaml dan event konstantalarini generatsiya qiladi.

Chiqish:
  libs/py-common/src/medbron_common/events/_catalog_gen.py   — `Events` + `CATALOG`
  libs/py-common/src/medbron_common/events/schemas/*.json     — sxemalar nusxasi (paket ichida)
  libs/go-common/events/catalog_gen.go                        — Go konstantalari + `Catalog`
  libs/go-common/events/schemas/*.json                        — sxemalar nusxasi (go:embed)

Ishlatish:
  python scripts/gen-events.py           # yozadi
  python scripts/gen-events.py --check   # CI: generatsiya qilingan fayllar eskirgan bo'lsa exit 1

Kodda event nomi HECH QACHON string bilan yozilmaydi — faqat shu konstantalar orqali
(BLUEPRINT 8.6). Shu fayl katalog va kod o'rtasidagi yagona ko'prik.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "contracts" / "events"
PY_OUT = ROOT / "libs" / "py-common" / "src" / "medbron_common" / "events" / "_catalog_gen.py"
PY_SCHEMAS = ROOT / "libs" / "py-common" / "src" / "medbron_common" / "events" / "schemas"
GO_OUT = ROOT / "libs" / "go-common" / "events" / "catalog_gen.go"
GO_SCHEMAS = ROOT / "libs" / "go-common" / "events" / "schemas"
SCHEMA_DIRS = (PY_SCHEMAS, GO_SCHEMAS)

NAME_RE = re.compile(r"^[a-z]+(_[a-z]+)*\.[a-z]+(_[a-z]+)*$")
HEADER = "Code generated by scripts/gen-events.py from contracts/events/catalog.yaml. DO NOT EDIT."


def load_catalog() -> dict[str, dict]:
    catalog = yaml.safe_load((CONTRACTS / "catalog.yaml").read_text())
    for event_type, spec in catalog.items():
        if not NAME_RE.match(event_type):
            sys.exit(f"noto'g'ri event nomi: {event_type!r} (kutilgan: <domen>.<o'tgan_zamon>)")
        if not (CONTRACTS / spec["schema"]).is_file():
            sys.exit(f"{event_type}: sxema fayli yo'q: {spec['schema']}")
        if not (spec.get("publisher") or spec.get("publishers")):
            sys.exit(f"{event_type}: publisher ko'rsatilmagan")
    return catalog


def publishers(spec: dict) -> list[str]:
    return list(spec.get("publishers") or [spec["publisher"]])


def py_const(event_type: str) -> str:
    return event_type.replace(".", "_").upper()


def go_const(event_type: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[._]", event_type))


def render_py(catalog: dict[str, dict]) -> str:
    out = [
        f'"""{HEADER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass(frozen=True, slots=True)",
        "class EventSpec:",
        "    event_type: str",
        "    version: int",
        "    publishers: tuple[str, ...]",
        "    consumers: tuple[str, ...]",
        "    schema: str",
        "    aggregate: str",
        "",
        "",
        "class Events:",
        '    """Event turlari konstantalari. Kodda string o\'rniga faqat shular ishlatiladi."""',
        "",
    ]
    for event_type in catalog:
        out.append(f'    {py_const(event_type)} = "{event_type}"')
    out += ["", "", "CATALOG: dict[str, EventSpec] = {"]
    for event_type, spec in catalog.items():
        pubs = ", ".join(f'"{p}"' for p in publishers(spec))
        cons = ", ".join(f'"{c}"' for c in spec["consumers"])
        out += [
            f"    Events.{py_const(event_type)}: EventSpec(",
            f'        event_type="{event_type}",',
            f"        version={int(spec['version'])},",
            f"        publishers=({pubs},),",
            f"        consumers=({cons},),",
            f'        schema="{spec["schema"]}",',
            f'        aggregate="{spec["aggregate"]}",',
            "    ),",
        ]
    out += ["}", ""]
    return "\n".join(out)


def render_go(catalog: dict[str, dict]) -> str:
    def strs(items):
        return "[]string{" + ", ".join(f'"{i}"' for i in items) + "}"

    out = [
        f"// {HEADER}",
        "",
        "package events",
        "",
        "// Event turlari konstantalari. Kodda string o'rniga faqat shular ishlatiladi.",
        "const (",
    ]
    width = max(len(go_const(e)) for e in catalog)
    for event_type in catalog:
        out.append(f'\t{go_const(event_type).ljust(width)} = "{event_type}"')
    out += [")", "", "// Catalog — contracts/events/catalog.yaml ning koddagi nusxasi.", "var Catalog = map[string]Spec{"]
    for event_type, spec in catalog.items():
        out += [
            f"\t{go_const(event_type)}: {{",
            f"\t\tEventType:  {go_const(event_type)},",
            f"\t\tVersion:    {int(spec['version'])},",
            f"\t\tPublishers: {strs(publishers(spec))},",
            f"\t\tConsumers:  {strs(spec['consumers'])},",
            f'\t\tSchema:     "{spec["schema"]}",',
            f'\t\tAggregate:  "{spec["aggregate"]}",',
            "\t},",
        ]
    out += ["}", ""]
    return "\n".join(out)


def schema_files() -> list[Path]:
    return sorted(CONTRACTS.glob("*.json"))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="faqat tekshirish, yozmaslik")
    args = parser.parse_args()

    catalog = load_catalog()
    targets = {PY_OUT: render_py(catalog), GO_OUT: render_go(catalog)}

    if args.check:
        stale = [p for p, content in targets.items() if not p.is_file() or p.read_text() != content]
        expected = {f.name for f in schema_files()}
        for schema_dir in SCHEMA_DIRS:
            actual = {f.name for f in schema_dir.glob("*.json")} if schema_dir.is_dir() else set()
            if expected != actual:
                stale.append(schema_dir)
            else:
                stale += [schema_dir / f.name for f in schema_files()
                          if (schema_dir / f.name).read_bytes() != f.read_bytes()]
        if stale:
            for p in stale:
                print(f"ESKIRGAN: {p.relative_to(ROOT)}", file=sys.stderr)
            print("`python scripts/gen-events.py` ni ishga tushiring va commit qiling.", file=sys.stderr)
            return 1
        print(f"OK: {len(catalog)} event, generatsiya qilingan fayllar yangi")
        return 0

    for path, content in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    for schema_dir in SCHEMA_DIRS:
        if schema_dir.exists():
            shutil.rmtree(schema_dir)
        schema_dir.mkdir(parents=True)
        for f in schema_files():
            shutil.copy2(f, schema_dir / f.name)
    print(f"{len(catalog)} event: {PY_OUT.relative_to(ROOT)}, {GO_OUT.relative_to(ROOT)}, schemas/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
