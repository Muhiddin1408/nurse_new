// SchemaSQL — outbox_events va processed_events (Python OutboxMixin/ProcessedEventMixin bilan
// AYNAN bir xil). Go servislari buni birinchi golang-migrate migratsiyasiga ko'chiradi.
const SchemaSQL = `
CREATE TABLE IF NOT EXISTS outbox_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        UUID         NOT NULL UNIQUE,
    aggregate_type  VARCHAR(64)  NOT NULL,
    aggregate_id    VARCHAR(64)  NOT NULL,
    event_type      VARCHAR(100) NOT NULL,
    event_version   SMALLINT     NOT NULL DEFAULT 1,
    payload         JSONB        NOT NULL,
    traceparent     VARCHAR(64),
    status          VARCHAR(16)  NOT NULL DEFAULT 'pending'
                    CONSTRAINT ck_outbox_events_status CHECK (status IN ('pending', 'published', 'failed')),
    attempts        INTEGER      NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_error      TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_outbox_events_pending ON outbox_events (next_attempt_at) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS ix_outbox_events_published_at ON outbox_events (published_at) WHERE status = 'published';

CREATE TABLE IF NOT EXISTS processed_events (
    event_id     UUID         PRIMARY KEY,
    event_type   VARCHAR(100) NOT NULL,
    processed_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_processed_events_processed_at ON processed_events (processed_at);
`

var (
	outboxPending   = promauto.NewGauge(prometheus.GaugeOpts{Name: "outbox_pending", Help: "Chop etilmagan outbox qatorlari"})
	outboxPublished = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "outbox_published_total", Help: "Brokerga chiqarilgan eventlar"}, []string{"event_type"})
	outboxPublishErrors = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "outbox_publish_errors_total", Help: "Publish urinishidagi xatolar"}, []string{"event_type"})
	outboxFailed = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "outbox_failed_total", Help: "MAX urinishdan keyin failed bo'lgan eventlar"}, []string{"event_type"})
)

// DBTX — pgx.Tx yoki pool (AddEvent faqat tranzaksiya ichida chaqirilishi kerak).
type DBTX interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
}

// Outbox — biznes yozuvi bilan BITTA tranzaksiyada event yozish.
type Outbox struct {
	Producer string
	Validate bool
}

// NewOutbox — validatsiya yoqilgan.
func NewOutbox(producer string) *Outbox { return &Outbox{Producer: producer, Validate: true} }

// AddEvent — eventni joriy tranzaksiyaga qo'shadi. Commit — chaqiruvchining ishi.
func (o *Outbox) AddEvent(ctx context.Context, tx DBTX, eventType, aggregateID string, data any) (Envelope, error) {
	spec, ok := events.Lookup(eventType)
	if !ok {
		return Envelope{}, fmt.Errorf("%q contracts/events/catalog.yaml da yo'q", eventType)
	}
	if !spec.HasPublisher(o.Producer) {
		return Envelope{}, fmt.Errorf("%s %s ni publish qila olmaydi (katalog: %v)", o.Producer, eventType, spec.Publishers)
	}
	traceID := ""
	if sc := trace.SpanContextFromContext(ctx); sc.IsValid() {
		traceID = sc.TraceID().String()
	}
	env, err := NewEnvelope(eventType, spec.Version, o.Producer, spec.Aggregate, aggregateID, data, traceID)
	if err != nil {
		return Envelope{}, err
	}
	payload, err := json.Marshal(env)
	if err != nil {
		return Envelope{}, err
	}
	if o.Validate {
		if err := events.ValidateJSON(payload); err != nil {
			return Envelope{}, err
		}
	}
	var tp *string
	if s := telemetry.Traceparent(ctx); s != "" {
		tp = &s
	}
	_, err = tx.Exec(ctx, `INSERT INTO outbox_events
		(event_id, aggregate_type, aggregate_id, event_type, event_version, payload, traceparent, status, attempts, next_attempt_at)
		VALUES ($1, $2, $3, $4, $5, $6, $7, 'pending', 0, now())`,
		env.EventID, env.AggregateType, env.AggregateID, env.EventType, env.EventVersion, payload, tp)
	return env, err
}

// EnvelopePublisher — relay uchun (testlarda soxtasi).
type EnvelopePublisher interface {
	Publish(ctx context.Context, payload []byte, traceparent string) error
}

// Relay — BLUEPRINT 8.4 algoritmi (Python OutboxRelay bilan bir xil).
type Relay struct {
	Pool           *pgxpool.Pool
	Publisher      EnvelopePublisher
	BatchSize      int
	PollInterval   time.Duration
	PublishTimeout time.Duration
	MaxAttempts    int
	BackoffBase    time.Duration
	BackoffMax     time.Duration
	Retention      time.Duration
	PurgeInterval  time.Duration
	GaugeInterval  time.Duration
}

// NewRelay — standart qiymatlar bilan.
func NewRelay(pool *pgxpool.Pool, pub EnvelopePublisher) *Relay {
	return &Relay{
		Pool: pool, Publisher: pub, BatchSize: 100, PollInterval: time.Second,
		PublishTimeout: DefaultPublishTimeout, MaxAttempts: 10,
		BackoffBase: time.Second, BackoffMax: 5 * time.Minute,
		Retention: 7 * 24 * time.Hour, PurgeInterval: time.Hour, GaugeInterval: 10 * time.Second,
	}
}

// Backoff — min(base*2^(n-1), max).
func (r *Relay) Backoff(attempts int) time.Duration {
	d := float64(r.BackoffBase) * math.Pow(2, float64(attempts-1))
	if d > float64(r.BackoffMax) {
		return r.BackoffMax
	}
	return time.Duration(d)
}

type outboxRow struct {
	id          int64
	eventType   string
	payload     []byte
	traceparent *string
	attempts    int
}

// RunOnce — bitta batch (FOR UPDATE SKIP LOCKED). Qaytaradi: qayta ishlangan qatorlar soni.
func (r *Relay) RunOnce(ctx context.Context) (int, error) {
	tx, err := r.Pool.Begin(ctx)
	if err != nil {
		return 0, err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	rows, err := tx.Query(ctx, `SELECT id, event_type, payload, traceparent, attempts FROM outbox_events
		WHERE status = 'pending' AND next_attempt_at <= now()
		ORDER BY id LIMIT $1 FOR UPDATE SKIP LOCKED`, r.BatchSize)
	if err != nil {
		return 0, err
	}
	batch, err := pgx.CollectRows(rows, func(row pgx.CollectableRow) (outboxRow, error) {
		var o outboxRow
		err := row.Scan(&o.id, &o.eventType, &o.payload, &o.traceparent, &o.attempts)
		return o, err
	})
	if err != nil {
		return 0, err
	}
	for _, row := range batch {
		if err := r.publishRow(ctx, tx, row); err != nil {
			return 0, err
		}
	}
	return len(batch), tx.Commit(ctx)
}

func (r *Relay) publishRow(ctx context.Context, tx pgx.Tx, row outboxRow) error {
	tp := ""
	if row.traceparent != nil {
		tp = *row.traceparent
	}
	pctx, cancel := context.WithTimeout(ctx, r.PublishTimeout)
	pubErr := r.Publisher.Publish(pctx, row.payload, tp)
	cancel()
	if pubErr == nil {
		outboxPublished.WithLabelValues(row.eventType).Inc()
		_, err := tx.Exec(ctx, `UPDATE outbox_events SET status = 'published', published_at = now(), last_error = NULL
			WHERE id = $1`, row.id)
		return err
	}
	outboxPublishErrors.WithLabelValues(row.eventType).Inc()
	attempts := row.attempts + 1
	msg := pubErr.Error()
	if len(msg) > 2000 {
		msg = msg[:2000]
	}
	if attempts >= r.MaxAttempts {
		outboxFailed.WithLabelValues(row.eventType).Inc()
		// ALERT: outbox failed > 0 — qo'lda tekshiriladi.
		slog.ErrorContext(ctx, "outbox event failed permanently", slog.Int64("id", row.id),
			slog.String("event_type", row.eventType), slog.String("error", msg))
		_, err := tx.Exec(ctx, `UPDATE outbox_events SET status = 'failed', attempts = $2, last_error = $3 WHERE id = $1`,
			row.id, attempts, msg)
		return err
	}
	slog.WarnContext(ctx, "outbox publish failed, will retry", slog.Int64("id", row.id),
		slog.Int("attempts", attempts), slog.String("error", msg))
	_, err := tx.Exec(ctx, `UPDATE outbox_events SET attempts = $2, last_error = $3, next_attempt_at = now() + $4::interval
		WHERE id = $1`, row.id, attempts, msg, fmt.Sprintf("%d milliseconds", r.Backoff(attempts).Milliseconds()))
	return err
}

// Purge — Retention dan eski published qatorlarni o'chiradi (failed TEGILMAYDI).
func (r *Relay) Purge(ctx context.Context) (int64, error) {
	tag, err := r.Pool.Exec(ctx, `DELETE FROM outbox_events WHERE status = 'published' AND published_at < now() - $1::interval`,
		fmt.Sprintf("%d seconds", int64(r.Retention.Seconds())))
	if err != nil {
		return 0, err
	}
	return tag.RowsAffected(), nil
}

// PendingCount — gauge uchun.
func (r *Relay) PendingCount(ctx context.Context) (int64, error) {
	var n int64
	err := r.Pool.QueryRow(ctx, `SELECT count(*) FROM outbox_events WHERE status = 'pending'`).Scan(&n)
	return n, err
}

// Run — ctx bekor qilinguncha (SIGTERM). Batch to'la bo'lsa darhol takrorlaydi.
func (r *Relay) Run(ctx context.Context) error {
	slog.InfoContext(ctx, "outbox relay started", slog.Int("batch_size", r.BatchSize))
	nextPurge, nextGauge := time.Now(), time.Now()
	for ctx.Err() == nil {
		processed, err := r.RunOnce(ctx)
		if err != nil && ctx.Err() == nil {
			slog.ErrorContext(ctx, "outbox relay iteration failed", slog.String("error", err.Error()))
		}
		now := time.Now()
		if now.After(nextGauge) {
			if n, err := r.PendingCount(ctx); err == nil {
				outboxPending.Set(float64(n))
			}
			nextGauge = now.Add(r.GaugeInterval)
		}
		if now.After(nextPurge) {
			if n, err := r.Purge(ctx); err == nil && n > 0 {
				slog.InfoContext(ctx, "outbox purged", slog.Int64("deleted", n))
			}
			nextPurge = now.Add(r.PurgeInterval)
		}
		if processed < r.BatchSize {
			select {
			case <-ctx.Done():
			case <-time.After(r.PollInterval):
			}
		}
	}
	slog.Info("outbox relay stopping")
	return nil
}
