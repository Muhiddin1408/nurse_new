CREATE TABLE IF NOT EXISTS outbox_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        UUID         NOT NULL UNIQUE,
    aggregate_type  VARCHAR(64)  NOT NULL,
    aggregate_id    VARCHAR(64)  NOT NULL,
    event_type      VARCHAR(100) NOT NULL,
    event_version   SMALLINT     NOT NULL DEFAULT 1,
    payload         JSONB        NOT NULL,
    traceparent     VARCHAR(64),
    status          VARCHAR(16)  NOT NULL DEFAULT 'pending'
                    CONSTRAINT ck_outbox_events_status CHECK (status IN ('pending', 'published', 'failed')),
    attempts        INTEGER      NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_error      TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_outbox_events_pending ON outbox_events (next_attempt_at) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS ix_outbox_events_published_at ON outbox_events (published_at) WHERE status = 'published';

CREATE TABLE IF NOT EXISTS processed_events (
    event_id     UUID         PRIMARY KEY,
    event_type   VARCHAR(100) NOT NULL,
    processed_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_processed_events_processed_at ON processed_events (processed_at);
